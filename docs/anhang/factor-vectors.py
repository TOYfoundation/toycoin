"""Generates test vectors for the emission factor m (spec 9.1).

Uses the reference formula from m-simulation.py, so the Rust code in
toychain/crates/toy-emission is checked against exactly the same rules.
Run: python3 docs/anhang/factor-vectors.py > toychain/crates/toy-emission/tests/vectors/factor_vectors.rs
"""

import importlib.util
import pathlib
import random

_spec = importlib.util.spec_from_file_location(
    "msim", pathlib.Path(__file__).with_name("m-simulation.py"))
msim = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(msim)
PPM = msim.PPM

rng = random.Random(20261018)
rows = []
for _ in range(64):
    m = rng.randint(500_000, 2_000_000)
    blocks = rng.choice([1440, 1441, 2000, 8640, rng.randint(1440, 10000)])
    paid = rng.choice([0, rng.randint(0, blocks * 1000), blocks * 500, blocks * 2000, rng.randint(0, 1000)])
    expected = rng.choice([21 * blocks, 128 * blocks, rng.randint(1, 10**9)])
    got = rng.choice([expected, 0, rng.randint(0, expected), expected * 67 // 100, expected * 95 // 100])
    plan = msim.plan_after_days(rng.randint(0, 20000))
    dev = rng.choice([0, rng.randint(-60_000, 60_000), rng.randint(-1000, 1000), rng.randint(-200_000, 200_000)])
    issued = 0 if plan == 0 else max(0, min(msim.SUPPLY, plan + plan * dev // PPM + rng.randint(-10**20, 10**20)))
    rows.append((m, blocks, paid, got, expected, issued, plan,
                 msim.next_m_with_plan(m, paid, blocks, got, expected, issued, plan)))

print("// Generated by docs/anhang/factor-vectors.py from the reference formula. Do not edit.")
print("// (m_prev, blocks, counted_tx, signatures_received, signatures_expected, issued, plan, m_next)")
print("pub type FactorVector = (u64, u64, u64, u64, u64, u128, u128, u64);")
print("pub const FACTOR_VECTORS: [FactorVector; %d] = [" % len(rows))
for r in rows:
    print("    (%s)," % ", ".join(str(x) for x in r))
print("];")
